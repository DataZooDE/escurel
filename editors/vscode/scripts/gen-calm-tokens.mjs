// Writes test/visual/tokens/calm.css: the --vscode-* tokens the Escurel Calm theme gives a webview,
// on top of the light set (a token the theme does not name keeps VS Code Light's value, as it would in
// a real window). Run it after editing themes/escurel-calm-color-theme.json.
//   node scripts/gen-calm-tokens.mjs           write test/visual/tokens/calm.css
//   node scripts/gen-calm-tokens.mjs --check   exit 1 if the committed calm.css is stale (npm run lint runs this)
import { readFileSync, writeFileSync } from 'node:fs';

const theme = JSON.parse(readFileSync('themes/escurel-calm-color-theme.json', 'utf8'));
const light = readFileSync('test/visual/tokens/light.css', 'utf8');
// VS Code's rule: every `.` of a colour id becomes `-`, case is kept (`sideBar.background` -> `sideBar-background`).
const name = (id) => `--vscode-${id.replaceAll('.', '-')}`;
const own = new Map(Object.entries(theme.colors).map(([id, v]) => [name(id), v]));
const lines = light.split('\n').map((l) => {
  const m = /^(\s*)(--vscode-[\w-]+):\s*(.+);$/.exec(l);
  return m && own.has(m[2]) ? `${m[1]}${m[2]}: ${own.get(m[2])};` : l;
});
const known = new Set(light.match(/--vscode-[\w-]+/g));
const extra = [...own].filter(([n]) => !known.has(n)).map(([n, v]) => `  ${n}: ${v};`);
const out = lines.join('\n').replace(/\}\s*$/, `${extra.join('\n')}\n}\n`);
const target = 'test/visual/tokens/calm.css';
const rendered = out.replace(
  /^\/\*.*\*\//,
  '/* The --vscode-* tokens the Escurel Calm theme injects (generated by scripts/gen-calm-tokens.mjs). */',
);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== rendered) {
    console.error(`${target} is stale: run  node scripts/gen-calm-tokens.mjs  and commit it`);
    process.exit(1);
  }
  console.log(`calm.css is in sync with the theme (${own.size} colours)`);
} else {
  writeFileSync(target, rendered);
  console.log(`calm.css: ${own.size} theme colours`);
}
