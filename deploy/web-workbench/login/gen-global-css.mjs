// Writes login/global.css = the Escurel Calm colour tokens + global.base.css. The login/error pages of
// code-server then use the SAME `--vscode-*` names as the extension's webviews, with the values taken from the
// theme file itself, so the two cannot drift:
//   colour id `a.b` of editors/vscode/themes/escurel-calm-color-theme.json -> `--vscode-a-b`
// The pages are ALWAYS the light Calm look, whatever the browser prefers: the workbench behind the login applies
// the Calm theme (a dark login in front of a light app would be the jarring part), so there is no dark variant.
//
//   node gen-global-css.mjs           # (re)write global.css
//   node gen-global-css.mjs --check   # exit 1 if the committed global.css is stale (the Docker build runs this)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ext = join(here, '..', '..', '..', 'editors', 'vscode');

// The theme colours the login/error pages use (VS Code colour ids).
export const USED = [
  'editor.background',
  'editorWidget.background',
  'sideBar.background',
  'widget.border',
  'foreground',
  'descriptionForeground',
  'input.background',
  'input.border',
  'input.foreground',
  'focusBorder',
  'button.background',
  'button.foreground',
  'button.border',
  'button.hoverBackground',
  'textLink.foreground',
  'textLink.activeForeground',
  'errorForeground',
  'titleBar.activeBackground',
  'titleBar.activeForeground',
  'titleBar.border',
  'activityBar.foreground',
];
const cssName = (id) => `--vscode-${id.replaceAll('.', '-')}`;

const theme = JSON.parse(readFileSync(join(ext, 'themes', 'escurel-calm-color-theme.json'), 'utf8')).colors;
export function lightTokens() {
  return USED.map((id) => {
    if (!(id in theme)) throw new Error(`the Calm theme does not define ${id}`);
    return [cssName(id), theme[id]];
  });
}
export function build() {
  const rows = lightTokens().map(([n, v]) => `  ${n}: ${v};`).join('\n');
  const base = readFileSync(join(here, 'global.base.css'), 'utf8');
  return `/* GENERATED by gen-global-css.mjs from the Escurel Calm theme: do not edit; change global.base.css or the
   theme and run \`node gen-global-css.mjs\`. */
:root {
  color-scheme: light;
${rows}
}

${base}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(here, 'global.css');
  const text = build();
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(out, 'utf8');
    } catch {
      /* missing */
    }
    if (have !== text) {
      console.error('login/global.css is stale: run `node deploy/web-workbench/login/gen-global-css.mjs`');
      process.exit(1);
    }
    console.log('login/global.css is in sync with the Calm theme');
  } else {
    writeFileSync(out, text);
    console.log(`global.css: ${USED.length} theme colours`);
  }
}
